// Generates catalog.mjs from 11_3D_ASSET_LIBRARY/families.json and 09_JEWELRY_ENGINE/materials.json.
// Only families that services/geometry builds are listed (IMPLEMENTED); `--check` fails on drift.
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const root = join(here, "..", "..");
// Keep in sync with services/geometry/aurea_geometry/build.py GENERATORS (test/catalog.test.mjs checks it).
export const IMPLEMENTED = ["ring.classic", "ring.02", "pendant.01", "pendant.02"];
const EN_NAMES = { "ring.classic": "Classic band", "ring.02": "Comfort fit", "pendant.01": "Disc", "pendant.02": "Oval" };
const PARAM_NAMES = {
  innerDiameter: { es: "Diámetro interior", en: "Inner diameter" },
  bandWidth: { es: "Ancho", en: "Band width" },
  radialThickness: { es: "Grosor", en: "Thickness" },
  width: { es: "Ancho", en: "Width" },
  height: { es: "Alto", en: "Height" },
  thickness: { es: "Grosor", en: "Thickness" },
};

const library = JSON.parse(readFileSync(join(root, "11_3D_ASSET_LIBRARY", "families.json"), "utf8"));
const materials = JSON.parse(readFileSync(join(root, "09_JEWELRY_ENGINE", "materials.json"), "utf8"));
const families = IMPLEMENTED.map((id) => {
  const f = library.find((x) => x.id === id);
  if (!f) throw new Error(`family ${id} missing from families.json`);
  return {
    id: f.id,
    version: f.version,
    category: f.category,
    name: { es: f.name, en: EN_NAMES[id] },
    parameters: Object.entries(f.parameters).map(([name, p]) => {
      if (!PARAM_NAMES[name]) throw new Error(`no label for parameter ${name}`);
      return { name, label: PARAM_NAMES[name], min: p.min, max: p.max, default: p.default, unit: p.unit };
    }),
  };
});

const out = `// GENERATED by packages/design/build.mjs from 11_3D_ASSET_LIBRARY/families.json and
// 09_JEWELRY_ENGINE/materials.json. Do not edit.
export const FAMILIES = ${JSON.stringify(families, null, 2)};

export const MATERIALS_VERSION = ${JSON.stringify(materials.version)};
export const MATERIALS = ${JSON.stringify(materials.materials, null, 2)};
`;
const target = join(here, "catalog.mjs");
if (process.argv.includes("--check")) {
  if (readFileSync(target, "utf8") !== out) {
    console.error("packages/design/catalog.mjs is stale: run `pnpm --filter @aurea/design build`");
    process.exit(1);
  }
} else {
  writeFileSync(target, out);
}
