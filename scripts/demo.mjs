// Demo stack (hito 600): one command per step, all against .env.demo and compose.demo.yaml, which
// are physically separate from local development (.env, compose.yaml): own database, Keycloak
// realm, ports and artifact folder. Synthetic data and simulated providers only.
//
//   pnpm demo bootstrap        create .env.demo with random passwords (git-ignored, never printed)
//   pnpm demo up | down        start / stop PostgreSQL, Valkey and Keycloak of the demo (volumes kept)
//   pnpm demo reset --yes      erase the demo database, migrate and load the synthetic dataset
//   pnpm demo worker           geometry worker on 3911 (Python venv of services/geometry)
//   pnpm demo api              API on 3901
//   pnpm demo web              command center (panel) on 3101
//   pnpm demo reverse          adb reverse of the demo ports to the phone connected by USB
//   pnpm demo password [--staff] [--enter] [-s SERIAL]   type a demo password on the phone
//   pnpm demo status           which demo services answer
//
// Every command refuses unless .env.demo says AUREA_ENV=demo. Children get only the demo
// variables (local AUREA/KC/DATABASE/... values in the shell are dropped), so a shell that loaded
// the local .env cannot point the demo at the local database, or the other way round.
import { spawn, spawnSync } from "node:child_process";
import { randomBytes } from "node:crypto";
import { appendFileSync, existsSync, readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";
import { fileURLToPath } from "node:url";
import { envValue } from "./dev-password.mjs";

const ROOT = fileURLToPath(new URL("..", import.meta.url));
export const DEMO_ENV_FILE = join(ROOT, ".env.demo");
export const PORTS = { postgres: 5434, valkey: 6381, keycloak: 8180, worker: 3911, api: 3901, web: 3101 };
export const DEMO_REALM = "aurea-demo";

export function demoEnv({ root = ROOT, random = () => randomBytes(24).toString("hex") } = {}) {
  const pg = random();
  const vk = random();
  const p = PORTS;
  return [
    "# Generated by pnpm demo bootstrap for the demo stack (hito 600). Synthetic data only. Do not commit.",
    "AUREA_ENV=demo",
    `POSTGRES_PASSWORD=${pg}`,
    `VALKEY_PASSWORD=${vk}`,
    `DATABASE_URL=postgresql://aurea_demo:${pg}@127.0.0.1:${p.postgres}/aurea_demo`,
    `VALKEY_URL=redis://:${vk}@127.0.0.1:${p.valkey}`,
    `KC_BOOTSTRAP_ADMIN_PASSWORD=${random()}`,
    `KC_DEMO_CUSTOMER_PASSWORD=${random()}`,
    `KC_DEMO_STAFF_PASSWORD=${random()}`,
    `KC_WEB_CLIENT_SECRET=${random()}`,
    `OIDC_ISSUER=http://127.0.0.1:${p.keycloak}/realms/${DEMO_REALM}`,
    "OIDC_AUDIENCE=aurea-api",
    `GEOMETRY_WORKER_URL=http://127.0.0.1:${p.worker}`,
    `GEOMETRY_WORKER_PORT=${p.worker}`,
    `GEOMETRY_WORKER_SECRET=${random()}`,
    `FILE_URL_SECRET=${random()}`,
    `ARTIFACT_DIR=${join(root, ".data", "demo", "artifacts")}`,
    "PAYMENT_PROVIDER=simulated",
    `PAYMENT_WEBHOOK_SECRET=${random()}`,
    "AI_PROVIDER=simulated",
    `API_PORT=${p.api}`,
    `API_PUBLIC_URL=http://127.0.0.1:${p.api}`,
    `WEB_ORIGIN=http://127.0.0.1:${p.web}`,
    `WEB_SESSION_SECRET=${random()}`,
    "",
  ].join("\n");
}

const keyOf = (line) => (line && !line.startsWith("#") && line.includes("=") ? line.split("=", 1)[0].trim() : null);

/** Parses env text into an object (same rules as envValue: KEY=VALUE, # comments). */
export function parseEnv(text) {
  const out = {};
  for (const line of text.split(/\r?\n/)) {
    const k = keyOf(line);
    if (k) out[k] = envValue(line, k);
  }
  return out;
}

// Prefixes of the variables the AUREA processes read. A child never inherits them from the shell.
const APP_PREFIXES = ["AUREA_", "KC_", "OIDC_", "DATABASE_", "TEST_DATABASE_", "VALKEY_", "POSTGRES_", "GEOMETRY_", "FILE_URL_",
  "ARTIFACT_", "PAYMENT_", "PRICING_", "AI_", "API_", "WEB_", "JOB_", "EXPO_PUBLIC_", "NEXT_DIST_DIR"];

/** Shell environment without any AUREA variable, plus the demo values. */
export function childEnv(shell, demo) {
  const clean = Object.fromEntries(Object.entries(shell).filter(([k]) => !APP_PREFIXES.some((p) => k.toUpperCase().startsWith(p))));
  return { ...clean, ...demo };
}

/** Reads .env.demo and fails closed unless it is a complete demo file. */
export function loadDemo(text) {
  const env = parseEnv(text);
  if (env.AUREA_ENV !== "demo") throw new Error(`.env.demo dice AUREA_ENV=${env.AUREA_ENV ?? "(sin valor)"}; solo demo`);
  const missing = keyLines(demoEnv({ random: () => "x" })).filter((k) => !env[k]);
  if (missing.length) throw new Error(`.env.demo incompleto (${missing.join(", ")}): ejecuta pnpm demo bootstrap`);
  const db = new URL(env.DATABASE_URL);
  if (db.hostname !== "127.0.0.1" || db.pathname !== "/aurea_demo") throw new Error("DATABASE_URL de .env.demo no es la base aurea_demo local");
  return env;
}

const keyLines = (text) => text.split("\n").map(keyOf).filter(Boolean);

function run(cmd, args, opts = {}) {
  const r = spawnSync(cmd, args, { stdio: "inherit", shell: process.platform === "win32" && !opts.noShell, ...opts });
  if (r.error) throw new Error(`no se pudo ejecutar ${cmd}: ${r.error.code ?? r.error.message}`);
  if (r.status !== 0) throw new Error(`${cmd} ${args[0] ?? ""} terminó con código ${r.status}`);
}

/** Long-running child: forwards Ctrl+C and exits with its code. */
function serve(cmd, args, opts) {
  const child = spawn(cmd, args, { stdio: "inherit", shell: process.platform === "win32", ...opts });
  child.on("error", (e) => { console.error(`no se pudo ejecutar ${cmd}: ${e.code ?? e.message}`); process.exit(1); });
  child.on("exit", (code) => process.exit(code ?? 0));
  for (const s of ["SIGINT", "SIGTERM"]) process.on(s, () => child.kill(s));
}

function compose(env, ...args) {
  run("docker", ["compose", "-f", join(ROOT, "compose.demo.yaml"), "--env-file", DEMO_ENV_FILE, ...args], { env });
}

async function probe(url) {
  try {
    const r = await fetch(url, { signal: AbortSignal.timeout(2000) });
    return r.ok ? "ok" : `HTTP ${r.status}`;
  } catch {
    return "sin respuesta";
  }
}

function workerCommand() {
  const venv = join(ROOT, "services", "geometry", ".venv");
  const exe = process.platform === "win32" ? join(venv, "Scripts", "aurea-geometry-worker.exe") : join(venv, "bin", "aurea-geometry-worker");
  return existsSync(exe) ? exe : "aurea-geometry-worker";
}

export const COMMANDS = ["bootstrap", "up", "down", "reset", "worker", "api", "web", "reverse", "password", "status"];

async function main(argv) {
  const [cmd, ...rest] = argv;
  if (!COMMANDS.includes(cmd)) throw new Error(`uso: pnpm demo <${COMMANDS.join("|")}>`);
  if (cmd === "bootstrap") {
    if (process.env.AUREA_ENV === "production") throw new Error("AUREA_ENV=production: el demo nunca se crea junto a producción");
    const fresh = demoEnv();
    if (!existsSync(DEMO_ENV_FILE)) {
      writeFileSync(DEMO_ENV_FILE, fresh, { mode: 0o600 });
      console.log(".env.demo creado con contraseñas aleatorias (no se muestran)");
    } else {
      const current = readFileSync(DEMO_ENV_FILE, "utf8");
      const have = new Set(keyLines(current));
      const add = fresh.split("\n").filter((l) => keyOf(l) && !have.has(keyOf(l)));
      if (add.length) appendFileSync(DEMO_ENV_FILE, `${current.endsWith("\n") ? "" : "\n"}${add.join("\n")}\n`);
      console.log(add.length ? `.env.demo existía; se añadieron ${add.map(keyOf).join(", ")}` : ".env.demo ya estaba completo");
    }
    return;
  }
  if (!existsSync(DEMO_ENV_FILE)) throw new Error(".env.demo no existe: ejecuta pnpm demo bootstrap");
  const demo = loadDemo(readFileSync(DEMO_ENV_FILE, "utf8"));
  const env = childEnv(process.env, demo);
  switch (cmd) {
    case "up":
      return compose(env, "up", "-d", "--wait");
    case "down":
      return compose(env, "down"); // keeps the volumes; `reset` is the way to erase data
    case "reset":
      if (!rest.includes("--yes")) throw new Error("reset borra la base del demo (aurea_demo); repite con --yes");
      run(process.execPath, ["src/reset-demo.mjs", "--yes"], { cwd: join(ROOT, "packages", "db"), env, noShell: true });
      return;
    case "worker":
      return serve(workerCommand(), [], { env });
    case "api":
      run("pnpm", ["--filter", "@aurea/api", "build"], { env });
      return serve(process.execPath, ["dist/main.js"], { cwd: join(ROOT, "apps", "api"), env, shell: false });
    case "web": {
      const webEnv = { ...env, NEXT_DIST_DIR: ".next-demo" };
      const next = ["scripts/next.mjs"];
      const cwd = join(ROOT, "apps", "web");
      run(process.execPath, [...next, "build"], { cwd, env: webEnv, noShell: true });
      return serve(process.execPath, [...next, "start", "--hostname", "127.0.0.1", "--port", String(PORTS.web)], { cwd, env: webEnv, shell: false });
    }
    case "reverse":
      // Keycloak and API only: the demo APK has its JS bundle inside, it does not need Metro.
      for (const port of [PORTS.keycloak, PORTS.api]) run("adb", [...serialArgs(rest), "reverse", `tcp:${port}`, `tcp:${port}`], { noShell: true });
      console.log(`adb reverse listo: ${PORTS.keycloak} (Keycloak) y ${PORTS.api} (API)`);
      return;
    case "password": {
      const key = rest.includes("--staff") ? "KC_DEMO_STAFF_PASSWORD" : "KC_DEMO_CUSTOMER_PASSWORD";
      const pw = demo[key];
      if (!/^[0-9a-f]{16,128}$/.test(pw)) throw new Error(`${key} no es el valor hexadecimal de pnpm demo bootstrap; escríbela a mano`);
      for (const call of [["shell", "input", "text", pw], ...(rest.includes("--enter") ? [["shell", "input", "keyevent", "66"]] : [])]) {
        // stdio ignored on purpose: the password is an argument and must not be echoed anywhere.
        const r = spawnSync("adb", [...serialArgs(rest), ...call], { stdio: ["ignore", "ignore", "pipe"] });
        if (r.error) throw new Error(`no se pudo ejecutar adb: ${r.error.code ?? r.error.message}`);
        if (r.status !== 0) throw new Error("adb falló: ¿teléfono conectado y autorizado? (adb devices)");
      }
      console.log(`Contraseña de ${key === "KC_DEMO_STAFF_PASSWORD" ? "demo.equipo" : "demo.cliente"} escrita en el teléfono (no se muestra).`);
      return;
    }
    case "status": {
      const p = PORTS;
      const rows = [
        ["Keycloak", `http://127.0.0.1:${p.keycloak}/realms/${DEMO_REALM}/.well-known/openid-configuration`],
        ["Worker", `http://127.0.0.1:${p.worker}/healthz`],
        ["API", `http://127.0.0.1:${p.api}/readyz`],
        ["Panel", `http://127.0.0.1:${p.web}/`],
      ];
      for (const [name, url] of rows) console.log(`${name.padEnd(9)} ${url.split("/").slice(0, 3).join("/").padEnd(24)} ${await probe(url)}`);
      return;
    }
  }
}

function serialArgs(rest) {
  const serial = rest.includes("-s") ? rest[rest.indexOf("-s") + 1] : process.env.ANDROID_SERIAL;
  return serial ? ["-s", serial] : [];
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  main(process.argv.slice(2)).catch((e) => {
    console.error(e.message);
    process.exit(1);
  });
}
