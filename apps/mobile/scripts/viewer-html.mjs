// Builds the self-contained preview viewer page (src/design/viewer/viewer.js + three.js, MIT) into
// src/design/viewer/viewer.generated.ts. No bundler: each module becomes a blob: URL inside the page and
// its imports are rewritten to those URLs, so the page needs no network at all.
//   node scripts/viewer-html.mjs           # write (git-ignored; run by test, bundle and start)
//   node scripts/viewer-html.mjs --html f  # also write the plain page, for a browser smoke test
import { createHash } from "node:crypto";
import { readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";
import { fileURLToPath } from "node:url";

const APP = fileURLToPath(new URL("..", import.meta.url));
const THREE = join(APP, "node_modules/three");
const read = (p) => readFileSync(join(THREE, p), "utf8");
const version = JSON.parse(read("package.json")).version;

// Order matters: a module is defined after everything it imports.
const modules = [
  ["core", read("build/three.core.js")],
  ["three", read("build/three.module.js")],
  ["bgu", read("examples/jsm/utils/BufferGeometryUtils.js")],
  ["sku", read("examples/jsm/utils/SkeletonUtils.js")],
  ["gltf", read("examples/jsm/loaders/GLTFLoader.js")],
  ["room", read("examples/jsm/environments/RoomEnvironment.js")],
  ["viewer", readFileSync(join(APP, "src/design/viewer/viewer.js"), "utf8")],
];
const rewrites = {
  three: [["'./three.core.js'", "core"]],
  bgu: [["'three'", "three"]],
  sku: [["'three'", "three"]],
  gltf: [["'three'", "three"], ["'../utils/BufferGeometryUtils.js'", "bgu"], ["'../utils/SkeletonUtils.js'", "sku"]],
  room: [["'three'", "three"]],
  viewer: [['"three"', "three"], ['"three/addons/loaders/GLTFLoader.js"', "gltf"], ['"three/addons/environments/RoomEnvironment.js"', "room"]],
};
for (const [name, from] of Object.entries(rewrites)) {
  const src = modules.find(([n]) => n === name)[1];
  for (const [spec] of from) if (!src.includes(`from ${spec}`)) throw new Error(`${name}: import ${spec} not found (three ${version} changed?)`);
}

const boot = `
const SRC = ${JSON.stringify(Object.fromEntries(modules))};
const REWRITES = ${JSON.stringify(rewrites)};
const urls = {};
for (const name of ${JSON.stringify(modules.map(([n]) => n))}) {
  let text = SRC[name];
  for (const [spec, dep] of REWRITES[name] || []) text = text.split("from " + spec).join("from " + JSON.stringify(urls[dep]));
  urls[name] = URL.createObjectURL(new Blob([text], { type: "text/javascript" }));
}
import(urls.viewer).catch(() => window.ReactNativeWebView && window.ReactNativeWebView.postMessage(JSON.stringify({ type: "error", code: "VIEWER_FAILED" })));
`;
const html = `<!doctype html><html><head><meta charset="utf-8">
<meta name="viewport" content="width=device-width,initial-scale=1,maximum-scale=1,user-scalable=no">
<meta http-equiv="Content-Security-Policy" content="default-src 'none'; script-src 'unsafe-inline' blob:; style-src 'unsafe-inline'; img-src blob: data:; connect-src blob: data:">
<style>html,body{margin:0;height:100%;background:#0c0c0d;overflow:hidden;touch-action:none}canvas{display:block;width:100%;height:100%}</style>
</head><body><canvas id="c"></canvas><script>${boot.replace(/<\/script/gi, "<\\/script")}</script></body></html>`;

const sha = createHash("sha256").update(html).digest("hex");
writeFileSync(join(APP, "src/design/viewer/viewer.generated.ts"),
  `// GENERATED by scripts/viewer-html.mjs from three@${version} (MIT) and viewer.js. Do not edit or commit.\n` +
  `export const VIEWER_THREE_VERSION = ${JSON.stringify(version)};\nexport const VIEWER_SHA256 = ${JSON.stringify(sha)};\n` +
  `export const VIEWER_HTML = ${JSON.stringify(html)};\n`);
const i = process.argv.indexOf("--html");
if (i > 0) writeFileSync(process.argv[i + 1], html);
console.log(`viewer: three ${version}, ${(html.length / 1024).toFixed(0)} KiB, sha256 ${sha.slice(0, 12)}`);
