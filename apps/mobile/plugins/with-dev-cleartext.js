// Android blocks plain http in release builds. Local and CI builds talk to Keycloak and the API over
// http on the developer's machine (reached from the phone through `adb reverse`), so this plugin
// allows cleartext only for those exact hosts, and only when EXPO_PUBLIC_AUREA_ENV is local or ci.
// Every other host, and every demo/production build, keeps Android's default: https only.
const fs = require("node:fs");
const path = require("node:path");
const { withAndroidManifest, withDangerousMod } = require("expo/config-plugins");

const DEV_ENVS = new Set(["local", "ci"]);

/** Hostnames that may use http: the http issuer/API hosts of a local/ci build, plus localhost for Metro. */
function cleartextHosts(env) {
  if (!DEV_ENVS.has(env.EXPO_PUBLIC_AUREA_ENV)) return [];
  const hosts = new Set(["localhost"]);
  for (const name of ["EXPO_PUBLIC_OIDC_ISSUER", "EXPO_PUBLIC_API_URL"]) {
    const value = env[name];
    if (!value) throw new Error(`${name} is required for a ${env.EXPO_PUBLIC_AUREA_ENV} build`);
    const u = new URL(value);
    if (u.protocol === "http:") hosts.add(u.hostname);
  }
  return [...hosts].sort();
}

function networkSecurityXml(hosts) {
  const domains = hosts.map((h) => `    <domain includeSubdomains="false">${h}</domain>`).join("\n");
  return `<?xml version="1.0" encoding="utf-8"?>
<!-- Generated by plugins/with-dev-cleartext.js for a local/ci build. -->
<network-security-config>
  <base-config cleartextTrafficPermitted="false" />
  <domain-config cleartextTrafficPermitted="true">
${domains}
  </domain-config>
</network-security-config>
`;
}

const XML_REF = "@xml/network_security_config";

/**
 * Applies (local/ci) or removes (demo/production) the policy. Removal matters when an existing
 * android/ folder from a dev build is regenerated without --clean: the old XML and manifest
 * reference would otherwise survive into a production build.
 */
function withDevCleartext(config) {
  const hosts = cleartextHosts(process.env);
  config = withDangerousMod(config, [
    "android",
    (c) => {
      const dir = path.join(c.modRequest.platformProjectRoot, "app/src/main/res/xml");
      const file = path.join(dir, "network_security_config.xml");
      if (hosts.length) {
        fs.mkdirSync(dir, { recursive: true });
        fs.writeFileSync(file, networkSecurityXml(hosts));
      } else {
        fs.rmSync(file, { force: true });
      }
      return c;
    },
  ]);
  return withAndroidManifest(config, (c) => {
    applyToManifest(c.modResults, hosts);
    return c;
  });
}

function applyToManifest(manifest, hosts) {
  const app = manifest.manifest.application[0];
  if (hosts.length) {
    app.$["android:networkSecurityConfig"] = XML_REF;
    delete app.$["android:usesCleartextTraffic"];
  } else if (app.$["android:networkSecurityConfig"] === XML_REF) {
    delete app.$["android:networkSecurityConfig"];
  }
  return manifest;
}

module.exports = withDevCleartext;
module.exports.cleartextHosts = cleartextHosts;
module.exports.networkSecurityXml = networkSecurityXml;
module.exports.applyToManifest = applyToManifest;
